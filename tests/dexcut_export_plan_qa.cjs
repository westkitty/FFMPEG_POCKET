'use strict';
const assert=require('node:assert/strict');
const P=require('../dexcut-project.js');
const E=require('../dexcut-export-plan.js');
const s=P.micros;
let p=P.newProject('Composer');
const a={id:'s1',name:'source.mp4',kind:'video',sizeBytes:1000000,durationUs:s(12)};
p=P.apply(p,{type:'ADD_ASSET',data:{asset:a}});
const c=P.makeClip(a,0,s(12));
p=P.apply(p,{type:'ADD_CLIP',data:{clip:c}});
p=P.apply(p,{type:'SET_RANGES',data:{id:c.id,ranges:[[0,s(3)],[s(6),s(8)],[s(10),s(12)]]}});
let x=E.preflight(p,[{assetId:'s1',file:{}}],{verified:true,filters:['concat'],encoders:['libx264']},{multiInputVerified:true});
assert.equal(x.estimates.durationUs,s(7));
assert.equal(x.nodes.filter(n=>n.kind==='segment').length,3);
assert.equal(x.problems.length,0);
assert.equal(x.output.width,720);
x=E.preflight(p,[],{verified:true,filters:[],encoders:['libx264']});
assert(x.problems.some(v=>v.includes('Relink')));
assert(x.problems.some(v=>v.includes('concat')));
assert.equal(x.verdict,'blocked');
p=P.apply(p,{type:'SET_EXPORT',data:{targetSizeBytes:100}});
x=E.preflight(p,[{assetId:'s1'}],{verified:true,filters:['concat'],encoders:['libx264']});
assert(x.problems.some(v=>v.includes('too small')));
assert(x.warnings.some(v=>v.includes('estimate')));
p=P.apply(p,{type:'SET_EXPORT',data:{targetSizeBytes:null}});
x=E.preflight(p,[{assetId:'s1'}],{verified:true,filters:['concat'],encoders:['libx264']},{maxInputBytes:500000});
assert(x.problems.some(v=>v.includes('measured safe')));
console.log('PASS: capability-aware export planning and honest memory blockers');
